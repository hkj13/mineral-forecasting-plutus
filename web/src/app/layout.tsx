import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { ThemeProvider } from "@/context/ThemeContext";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Mineral Forecasting Platform | Plutus Hackathon 2025",
  description: "AI-powered critical mineral trade analytics and forecasting for India. Analyze Copper, Lithium, and Graphite trade flows, run ML forecasts, and simulate policy scenarios.",
  keywords: ["minerals", "forecasting", "trade", "India", "EXIM", "Copper", "Lithium", "Graphite", "ML", "analytics"],
  authors: [{ name: "Plutus Hackathon Team" }],
  openGraph: {
    title: "Mineral Forecasting Platform",
    description: "India's Critical Mineral Intelligence Platform",
    type: "website",
  },
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" data-theme="light" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `
              (function() {
                try {
                  var theme = localStorage.getItem('theme-preference') || 'light';
                  document.documentElement.setAttribute('data-theme', theme);
                } catch (e) {}
              })();
            `,
          }}
        />
      </head>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <ThemeProvider>
          {children}
        </ThemeProvider>
      </body>
    </html>
  );
}
